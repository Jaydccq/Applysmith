func TestDependencyBudgets(t *testing.T) {
	goMod := func(n int) string {
		var b strings.Builder
		b.WriteString("module m\n\ngo 1.27.1\n\nrequire (\n")
		for i := 0; i < n; i++ {
			fmt.Fprintf(&b, "\texample.com/d%d v1.0.0\n", i)
		}
		b.WriteString("\texample.com/indirect v1.0.0 // indirect\n)\n")
		return b.String()
	}
	pkgJSON := func(n int) string {
		deps := make([]string, n)
		for i := range deps {
			deps[i] = fmt.Sprintf("%q: \"1.0.0\"", fmt.Sprintf("p%d", i))
		}
		return `{"dependencies": {` + strings.Join(deps, ",") + `}, "devDependencies": {"dev": "1.0.0"}}`
	}
	tests := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{"go at the limit", map[string]string{"go.mod": goMod(20)}, nil},
		{"twenty-first go dependency", map[string]string{"go.mod": goMod(21)}, []string{"go.mod"}},
		{"dashboard at the limit", map[string]string{"web/package.json": pkgJSON(10)}, nil},
		{"dashboard over", map[string]string{"web/package.json": pkgJSON(11)}, []string{"web/package.json"}},
		{"engine runtime dependency", map[string]string{"engine/package.json": pkgJSON(1)}, []string{"engine/package.json"}},
		{"extension runtime dependency", map[string]string{"extension/package.json": pkgJSON(1)}, []string{"extension/package.json"}},
		{"engine dev dependencies only", map[string]string{"engine/package.json": `{"devDependencies": {"x": "1.0.0"}}`}, nil},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			fs, err := checkDependencyBudgets(dirTree(t, tc.files))
			if err != nil {
				t.Fatal(err)
			}
			if got := paths(fs); strings.Join(got, ",") != strings.Join(tc.want, ",") {
				t.Fatalf("flagged %v, want %v", got, tc.want)
			}
		})
	}
	fs, _ := checkDependencyBudgets(dirTree(t, map[string]string{"go.mod": goMod(21)}))
	if !strings.Contains(fs[0].Detail, "example.com/d20") {
		t.Errorf("detail should list the requirements: %q", fs[0].Detail)
	}
}

func TestRegexpCompiles(t *testing.T) {
	const layers = "internal/guard 0\ninternal/lazyregexp 2 pure\ninternal/a 10\n"
	src := func(body string) string { return "package a\n\nimport \"regexp\"\n\n" + body + "\n" }
	tests := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{"a package-level compile runs at every start", map[string]string{
			"internal/a/a.go":  src("var re = regexp.MustCompile(`x+`)"),
			"internal/a/b.go":  src("var res = []*regexp.Regexp{regexp.MustCompile(`a`), regexp.MustCompile(`b`)}"),
			"cmd/tool/main.go": "package main\n\nimport \"regexp\"\n\nvar re, reErr = regexp.Compile(`x`)\n",
		}, []string{"cmd/tool/main.go", "internal/a/a.go", "internal/a/b.go", "internal/a/b.go"}},
		{"a fixed pattern compiled in a function runs on every call", map[string]string{
			"internal/a/a.go": src("func f(s string) bool { return regexp.MustCompile(`x+`).MatchString(s) }"),
			"internal/a/b.go": src("func g() { _ = regexp.MustCompile(`(?i)` + (`a` + `b`)) }"),
			"internal/a/c.go": src("func h() { go func() { _, _ = regexp.Compile(`y`) }() }"),
		}, []string{"internal/a/a.go", "internal/a/b.go", "internal/a/c.go"}},
		{"a pattern built at run time is compiled where it is built", map[string]string{
			"internal/a/a.go": src("func f(w string) *regexp.Regexp { return regexp.MustCompile(`\\b` + regexp.QuoteMeta(w) + `\\b`) }"),
		}, nil},
		{"a renamed import is still regexp", map[string]string{
			"internal/a/a.go": "package a\n\nimport re \"regexp\"\n\nvar x = re.MustCompile(`x`)\n",
		}, []string{"internal/a/a.go"}},
		{"lazyregexp, tests and packages that cannot import it are exempt", map[string]string{
			"internal/a/a.go":      "package a\n\nimport \"applysmith/internal/lazyregexp\"\n\nvar re = lazyregexp.New(`x`)\n",
			"internal/a/a_test.go": src("var re = regexp.MustCompile(`x`)"),
			"internal/guard/g.go":  src("var re = regexp.MustCompile(`x`)"),
			"internal/a/notes.md":  "var re = regexp.MustCompile(`x`)\n",
		}, nil},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			tc.files[layersFile] = layers
			fs, err := checkRegexpCompiles(dirTree(t, tc.files))
			if err != nil {
				t.Fatal(err)
			}
			if got := paths(fs); strings.Join(got, ",") != strings.Join(tc.want, ",") {
				t.Fatalf("flagged %v, want %v", got, tc.want)
			}
		})
	}
	fs, _ := checkRegexpCompiles(dirTree(t, map[string]string{layersFile: layers,
		"internal/a/a.go": src("var re = regexp.MustCompile(`x`)\n\nfunc f() { _ = regexp.MustCompile(`y`) }")}))
	if len(fs) != 2 || fs[0].Line != 5 || fs[0].Col != 10 || !strings.Contains(fs[0].Detail, "process start") || !strings.Contains(fs[1].Detail, "every call") {
		t.Errorf("findings = %+v", fs)
	}
	if fs, _ := checkRegexpCompiles(dirTree(t, map[string]string{layersFile: "internal/a 10\n"})); len(fs) != 1 || !strings.Contains(fs[0].Detail, "has no layer") {
		t.Errorf("without a layer for lazyregexp: %+v", fs)
	}
}

