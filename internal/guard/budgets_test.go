func TestFileLengthLimits(t *testing.T) {
	lines := func(n int) string { return strings.Repeat("x\n", n) }
	gen := "// Code generated by tool. DO NOT EDIT.\n" + lines(3000)
	tree := dirTree(t, map[string]string{
		"ok1200.go":      lines(1200),
		"over1201.go":    lines(1201),
		"over_test.go":   lines(1201),
		"ok1200.swift":   lines(1200),
		"over1201.swift": lines(1201),
		"ok1500.ts":      lines(1500),
		"over1501.tsx":   lines(1501),
		"generated.ts":   gen,
		"generated.go":   gen,
		"big.md":         lines(5000),
		"nofinalnl.go":   strings.Repeat("x\n", 1199) + "x",
		"nofinalnl2.go":  strings.Repeat("x\n", 1200) + "x",
	})
	fs, err := checkFileLength(tree)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"nofinalnl2.go", "over1201.go", "over1201.swift", "over1501.tsx", "over_test.go"}
	if got := paths(fs); strings.Join(got, ",") != strings.Join(want, ",") {
		t.Fatalf("flagged %v, want %v", got, want)
	}
	for _, f := range fs {
		if f.Path == "over1201.go" && !strings.Contains(f.Detail, "1201 lines (limit 1200)") {
			t.Errorf("detail = %q", f.Detail)
		}
	}
}

func TestRepositoryBudgets(t *testing.T) {
	t.Run("file count", func(t *testing.T) {
		files := map[string]string{}
		for i := 0; i <= maxTrackedFiles; i++ {
			files[fmt.Sprintf("f/%04d.txt", i)] = "x"
		}
		fs, _ := checkBudgets(dirTree(t, files))
		if len(fs) != 1 || !strings.Contains(fs[0].Detail, fmt.Sprintf("%d files (limit %d)", maxTrackedFiles+1, maxTrackedFiles)) {
			t.Fatalf("findings = %v", fs)
		}
		delete(files, fmt.Sprintf("f/%04d.txt", maxTrackedFiles))
		if fs, _ := checkBudgets(dirTree(t, files)); len(fs) != 0 {
			t.Fatalf("at the limit: %v", fs)
		}
	})
	t.Run("bytes list the ten largest", func(t *testing.T) {
		tree := dirTree(t, map[string]string{"small.txt": "x"})
		for i := 0; i < 31; i++ {
			p := fmt.Sprintf("big%02d.dat", i)
			writeFile(t, tree.Root, p, "")
			if err := os.Truncate(filepath.Join(tree.Root, p), 1_300_000+int64(i)); err != nil {
				t.Fatal(err)
			}
			tree.Paths = append(tree.Paths, p)
		}
		fs, _ := checkBudgets(tree)
		if len(fs) != 1 {
			t.Fatalf("findings = %v", fs)
		}
		d := fs[0].Detail
		if !strings.Contains(d, "limit 40000000") || !strings.Contains(d, "big30.dat") || strings.Contains(d, "big20.dat") || strings.Contains(d, "small.txt") {
			t.Errorf("detail = %q", d)
		}
	})
}

