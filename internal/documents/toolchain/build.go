package toolchain

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"applysmith/internal/lazyregexp"
)

// PairBudget is the compile, verify and repair budget of one document pair,
// bounded by the deadline of the run that owns it.
const PairBudget = 300 * time.Second

// Engines a build may name.
const (
	EngineLuaLaTeX = "lualatex"
	EngineXeLaTeX  = "xelatex"
)

// ErrStaleSource is returned when the TeX handed to a build is no longer the
// source its caller hashed: nothing is compiled over it.
var ErrStaleSource = errors.New("toolchain: the source changed after it was hashed")

// ErrBadName is returned for a build name the service did not generate.
var ErrBadName = errors.New("toolchain: invalid build name")

// buildName is the shape of a generated build name: a file stem, never a path.
var buildName = lazyregexp.New(`^[a-z][a-z0-9-]{0,39}$`)

// BuildInput is one document to compile: TeX the product itself rendered from
// a reviewed template, never request text. Name is generated by the caller.
type BuildInput struct {
	Name   string
	Engine string
	TeX    []byte
	// TeXSHA256, when set, is the hash of the TeX the caller rendered and
	// verified its content against; a build over other bytes is refused.
	TeXSHA256 string
	// Cover copies the cover class and the template fonts beside the source.
	Cover  bool
	Expect PDFExpect
	Layout LayoutExpect
}

// Preview is one rasterised page.
type Preview struct {
	Name   string
	PNG    []byte
	SHA256 string
}

// BuildOutput is a compiled and verified document. Verify and Layout are the
// accepted verifier results for exactly the bytes in PDF.
type BuildOutput struct {
	PDF       []byte
	PDFSHA256 string
	TeXSHA256 string
	Passes    int
	Pages     int
	Text      string
	Verify    PDFResult
	Layout    LayoutResult
	Previews  []Preview
}

// Build compiles in.TeX in a private scratch directory, verifies the PDF with
// the adapted scripts and rasterises previews, then removes the scratch
// directory. Failures are typed: ErrTimeout, ErrLogLimit, ErrCancelled,
// ErrVerdict, or an error naming the exceeded scratch or PDF limit. A verdict
// of fail or unverified is not an error; the caller decides what it permits.
func (t *Toolchain) Build(ctx context.Context, in BuildInput) (BuildOutput, error) {
	if in.Engine != EngineLuaLaTeX && in.Engine != EngineXeLaTeX {
		return BuildOutput{}, fmt.Errorf("toolchain: unknown engine %q", in.Engine)
	}
	if !buildName.MatchString(in.Name) {
		return BuildOutput{}, fmt.Errorf("%w: %q", ErrBadName, in.Name)
	}
	if in.TeXSHA256 != "" && in.TeXSHA256 != sha256Hex(in.TeX) {
		return BuildOutput{}, ErrStaleSource
	}
	build, err := t.newBuildDir()
	if err != nil {
		return BuildOutput{}, err
	}
	defer os.RemoveAll(build)
	dir := filepath.Join(build, in.Name)
	if err := os.Mkdir(dir, 0o700); err != nil {
		return BuildOutput{}, err
	}
	if in.Cover {
		if err := writeAssets(dir); err != nil {
			return BuildOutput{}, err
		}
	}
	if err := os.WriteFile(filepath.Join(dir, in.Name+".tex"), in.TeX, 0o600); err != nil {
		return BuildOutput{}, err
	}
	var out BuildOutput
	out.TeXSHA256 = sha256Hex(in.TeX)
	if out.Passes, err = t.compile(ctx, in.Engine, dir, in.Name); err != nil {
		if errors.Is(err, ErrCancelled) || errors.Is(err, ErrTimeout) || errors.Is(err, ErrLogLimit) {
			return out, err
		}
		return out, fmt.Errorf("%w (engine log kept at %s)", err, t.keepLog(dir, in.Name))
	}
	if err := dirWithin(dir, MaxScratchBytes); err != nil {
		return out, err
	}
	pdfPath := filepath.Join(dir, in.Name+".pdf")
	if out.PDFSHA256, _, err = fileSHA256(pdfPath); err != nil {
		return out, err
	}
	expect := in.Expect
	expect.DumpText = filepath.Join(dir, in.Name+".txt")
	if out.Verify, err = t.VerifyPDF(ctx, pdfPath, expect); err != nil {
		if !unverifiable(ctx, err) {
			return out, err
		}
		out.Verify = UnverifiedPDF(expect, out.PDFSHA256, reasonOf("verify_pdf", err))
	}
	if out.Verify.Pages != nil {
		out.Pages = *out.Verify.Pages
	}
	if out.Layout, err = t.VerifyLayout(ctx, pdfPath, in.Layout); err != nil {
		if !unverifiable(ctx, err) {
			return out, err
		}
		out.Layout = UnverifiedLayout(in.Layout, out.PDFSHA256, reasonOf("verify_layout", err))
	}
	if err := t.rasterise(ctx, dir, in.Name, &out); err != nil {
		return out, err
	}
	// The bytes returned are read last and must still be the ones both
	// verdicts describe.
	if out.PDF, err = os.ReadFile(pdfPath); err != nil {
		return out, err
	}
	if sha256Hex(out.PDF) != out.PDFSHA256 {
		return out, fmt.Errorf("%w: the PDF changed after it was verified", ErrVerdict)
	}
	if txt, err := os.ReadFile(expect.DumpText); err == nil {
		out.Text = string(txt)
	}
	return out, nil
}

// rasterise reads back the page previews pdftoppm wrote for the PDF.
func (t *Toolchain) rasterise(ctx context.Context, dir, name string, out *BuildOutput) error {
	if _, err := t.previews(ctx, dir, name); err != nil {
		return err
	}
	matches, _ := filepath.Glob(filepath.Join(dir, name+"-page*.png"))
	sort.Strings(matches)
	for _, m := range matches {
		b, err := os.ReadFile(m)
		if err != nil {
			return err
		}
		out.Previews = append(out.Previews, Preview{Name: filepath.Base(m), PNG: b, SHA256: sha256Hex(b)})
	}
	return nil
}

func sha256Hex(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

// unverifiable says whether a verifier failure leaves the PDF unverified, as
// opposed to stopping the build: a verifier that crashed, printed something
// unacceptable or lost its tool cannot vouch for the PDF, but a cancelled or
// timed-out run has no PDF to keep.
func unverifiable(ctx context.Context, err error) bool {
	return ctx.Err() == nil && !errors.Is(err, ErrCancelled) && !errors.Is(err, ErrTimeout) && !errors.Is(err, ErrLogLimit)
}

// reasonOf is the first line of a verifier failure; the rest may quote output.
func reasonOf(tool string, err error) string {
	line, _, _ := strings.Cut(err.Error(), "\n")
	return tool + " gave no accepted result: " + line
}
