package wire

// Reasons of the remote-access refusals.
const (
	// ReasonRemoteForbidden answers a remote call to a route the remote
	// allowlist does not contain.
	ReasonRemoteForbidden = "remote_forbidden"
	// ReasonBlocked answers a source that presented too many bad credentials.
	ReasonBlocked = "blocked"
	// ReasonDeviceLimit answers a pairing claim past the device limit.
	ReasonDeviceLimit = "device_limit"
	// ReasonTunnelIngress answers a request that came through a tunnel to the
	// primary listener, which only this computer may use.
	ReasonTunnelIngress = "tunnel_ingress"
)

// TunnelOff is the tunnel's state when no status file says otherwise.
const TunnelOff = "off"

// RemoteListener is one address the server listens on; every one is loopback.
type RemoteListener struct {
	Name    string `json:"name"`
	Address string `json:"address"`
}

// RemoteTunnel is the supervised tunnel's state. It holds no secret.
type RemoteTunnel struct {
	State               string  `json:"state"`
	PublicURL           string  `json:"publicUrl"`
	Version             string  `json:"version"`
	Reason              string  `json:"reason,omitempty"`
	Error               string  `json:"error,omitempty"`
	ConsecutiveFailures SafeInt `json:"consecutiveFailures"`
}

// RemoteStatus is the remote-access section of the dashboard: the mode the
// server is acting on, the addresses it listens on, the tunnel, and how many
// devices are paired and connected. Error names what keeps the tunnel
// listener closed while the mode asks for it.
type RemoteStatus struct {
	Mode             string           `json:"mode"`
	Listeners        []RemoteListener `json:"listeners"`
	Tunnel           RemoteTunnel     `json:"tunnel"`
	Error            string           `json:"error,omitempty"`
	AllowScreenshots bool             `json:"allowScreenshots"`
	Devices          SafeInt          `json:"devices"`
	Connected        SafeInt          `json:"connected"`
}

// RemoteQR is a QR code as rows of '0' (light) and '1' (dark) modules, without
// a quiet zone. It is generated by the server; no external service is used.
type RemoteQR struct {
	Size SafeInt  `json:"size"`
	Rows []string `json:"rows"`
}

// RemoteOffer is a pairing offer: the link to open on the phone, the same link
// as a QR code, and when the offer ends. The code is in the link's fragment.
type RemoteOffer struct {
	Link      string   `json:"link"`
	ExpiresAt Time     `json:"expiresAt"`
	QR        RemoteQR `json:"qr"`
}

// RemotePairClaim is what the pairing page posts: the code from the link and a
// label of 1 to 40 printable characters.
type RemotePairClaim struct {
	Code  string `json:"code"`
	Label string `json:"label"`
}

// RemoteClaimed answers a claim. The token is shown once and also set in the
// device cookie; Redirect is the dashboard on the configured origin.
type RemoteClaimed struct {
	DeviceID string `json:"deviceId"`
	Label    string `json:"label"`
	Token    string `json:"token"`
	Redirect string `json:"redirect"`
}

// RemoteDevice is a paired device.
type RemoteDevice struct {
	ID         string `json:"id"`
	Label      string `json:"label"`
	CreatedAt  Time   `json:"createdAt"`
	LastSeenAt *Time  `json:"lastSeenAt,omitempty"`
	Network    string `json:"network"`
	Connected  bool   `json:"connected"`
}

// RemoteDeviceList lists the paired devices, oldest first.
type RemoteDeviceList struct {
	Devices []RemoteDevice `json:"devices"`
}

// RemoteRevoked says how many devices a revoke ended.
type RemoteRevoked struct {
	Revoked SafeInt `json:"revoked"`
}

// RemoteMe tells a client which credential it is using. Kind is dashboard,
// local-token or remote-device; the device fields are set for the last.
type RemoteMe struct {
	Kind     string `json:"kind"`
	DeviceID string `json:"deviceId,omitempty"`
	Label    string `json:"label,omitempty"`
}

// RemoteEvent is one row of the remote audit. It holds no code or token.
type RemoteEvent struct {
	At       Time   `json:"at"`
	Kind     string `json:"kind"`
	DeviceID string `json:"deviceId,omitempty"`
	Source   string `json:"source"`
	Detail   string `json:"detail"`
}

// RemoteEventList lists the latest remote events, newest first.
type RemoteEventList struct {
	Events []RemoteEvent `json:"events"`
}
