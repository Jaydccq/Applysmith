func (s *Server) health(c *apikit.Call) (apikit.Reply, error) {
	// The status reads the cached database component. The components read now
	// cost a database read, so only a caller who is shown them pays for it.
	snapshot := s.components.Load()
	status := wire.HealthOK
	switch {
	case s.store.Load() == nil:
		status = wire.HealthStarting
	case snapshot.list[0].Status != wire.ComponentOK:
		status = wire.HealthDegraded
	}
	if requestIsRemote(c.R) {
		return apikit.Reply{Data: wire.Health{Status: status, APIVersion: wire.APIVersion}}, nil
	}
	h := wire.Health{
		Status: status, APIVersion: wire.APIVersion, Version: s.cfg.Version, BuildID: s.cfg.BuildID,
		PathKey: s.pathKey, StartedAt: wire.Time{Time: s.startedAt},
	}
	if c.P.Kind != apikit.PrincipalNone {
		up := wire.SafeInt(s.now().Sub(s.startedAt) / time.Second)
		schema := wire.SafeInt(store.SchemaVersion())
		h.UptimeSeconds, h.SchemaVersion, h.Components = &up, &schema, s.liveComponents(snapshot)
		h.ComponentsCheckedAt, h.ComponentsProbeMS = &snapshot.checkedAt, &snapshot.probeMS
	}
	return apikit.Reply{Data: h}, nil
}

func (s *Server) boardEvents(c *apikit.Call) (apikit.Reply, error) {
	err := s.serveStream(c, s.board.es, func() ([]sseEvent, bool) { return []sseEvent{s.board.snapshot()}, false })
	return apikit.Reply{}, err
}

func (s *Server) createPairingCode(c *apikit.Call) (apikit.Reply, error) {
	code, exp, err := s.pair.create()
	if err != nil {
		return apikit.Reply{}, err
	}
	return apikit.Reply{Data: wire.PairingCode{Code: code, ExpiresAt: wire.Time{Time: exp.UTC()}}}, nil
}

func (s *Server) claimPairingCode(c *apikit.Call) (apikit.Reply, error) {
	var req wire.PairingClaim
	if e := apikit.Decode(c.Body, &req); e != nil {
		return apikit.Reply{}, e
	}
	if !s.pair.claim(req.Code) {
		return apikit.Reply{}, apikit.NewErr(wire.CodeUnauthenticated, "the pairing code is not valid")
	}
	tok, err := s.cfg.Vault.Get(vault.APIToken)
	if err != nil {
		return apikit.Reply{}, err
	}
	return apikit.Reply{Data: wire.TokenIssued{Token: tok}}, nil
}

func (s *Server) rotateToken(c *apikit.Call) (apikit.Reply, error) {
	tok, err := s.RotateToken()
	switch {
	case errors.Is(err, ErrEnvManaged):
		return apikit.Reply{}, apikit.NewErr(wire.CodeConflict, "the API token is supplied by APPLYSMITH_SECRET_API_TOKEN; change it there")
	case err != nil:
		return apikit.Reply{}, err
	}
	return apikit.Reply{Data: wire.TokenIssued{Token: tok}}, nil
}
